      h2.
        1.4 Enfoques
    p.mb-4.
      Los enfoques permiten mirar la diversidad desde una perspectiva más amplia y no desde una mirada única. Porque no se trata solo de reconocer las diferencias, sino de comprender la manera como estas crean necesidades particulares de comunicación, atención o acceso. Es así, como los enfoques ayudan a las entidades a comunicarse desde una comprensión más cercana con las ciudadanías.
    p.mb-4.
      A continuación, se relacionan los enfoques más importantes:
    h5.mt-4.
      Enfoque de derechos
    p.mb-4.
      La información debe facilitar el ejercicio de derechos y la participación.
    h5.mt-4.
      Enfoque diferencial
    p.mb-4.
      Algunas personas requieren ajustes de acuerdo a sus condiciones.
    h5.mt-4.
      Enfoque territorial
    p.mb-4.
      El lugar donde viven las perdonas influye en el acceso a la información.
    h5.mt-4.
      Enfoque intercultural
    p.mb-4.
      Las prácticas, lengua y referentes culturales influyen en la comprensión.
    h5.mt-4.
      Enfoque inclusivo
    p.mb-4.
      La comunicación debe evitar exclusiones y reconocer la dignidad de las personas.
    p.mb-4.
      Los enfoques ayudan a mirar la diversidad con mayor cuidado. No se trata solo de reconocer que las personas son diferentes, sino de comprender qué condiciones pueden influir en la manera como reciben, entienden y usan la información.
    p.mb-4.
      Desde el enfoque de derechos, la comunicación debe facilitar que todas las personas accedan a la información, la comprendan y puedan usarla para participar o ejercer sus derechos. El enfoque diferencial, por su parte, permite identificar cuándo una persona o grupo requiere ajustes en el lenguaje, el canal, el formato o la atención que recibe.
    p.mb-4.
      También es importante tener en cuenta el enfoque territorial, porque el lugar donde viven las personas puede influir en la conectividad, los medios disponibles y el acceso a los servicios. El enfoque intercultural permite reconocer que algunas comunidades tienen lenguas, prácticas, saberes y formas propias de organización que deben ser consideradas al momento de comunicar.
    p.mb-4.
      Finalmente, el enfoque inclusivo invita a revisar que los mensajes no refuercen estereotipos, no excluyan a ningún grupo y reconozcan la dignidad de las personas.
    p.mb-4.
      Aplicar estos enfoques permite que la comunicación institucional sea más cercana, respetuosa y pertinente para las ciudadanías.

