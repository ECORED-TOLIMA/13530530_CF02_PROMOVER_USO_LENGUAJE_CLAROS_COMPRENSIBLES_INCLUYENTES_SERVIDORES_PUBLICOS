      h2.
        4.1 Concepto
    p.mb-4.
      La inclusión consiste en reconocer que las personas tienen diferentes formas de vivir, comunicarse, participar y acceder a la información. Por ello, no basta con que una persona esté presente en un proceso o servicio; también es necesario generar las condiciones para que pueda comprender la información, participar activamente y ejercer sus derechos sin enfrentar barreras.

